"""Builds data/history_2018_2026.json from official Banco Central (SGS) series plus the documented shock table."""

import json
import time
import urllib.request
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
RAW = DATA / "bcb"
START, END = "01/10/2016", "30/09/2026"

SERIES = {
    "selic": 4189,
    "ipca_12m": 13522,
    "brl_usd": 3696,
    "debt_gdp": 13762,
    "unemployment": 24369,
    "gdp_index": 22099,
    "primary_deficit_12m": 5793,
}
SOURCES = {
    "selic": "BCB SGS 4189 - Selic acumulada no mes anualizada (% a.a.)",
    "ipca_12m": "BCB SGS 13522 - IPCA acumulado em 12 meses (%)",
    "brl_usd": "BCB SGS 3696 - Dolar PTAX venda, fim de periodo mensal (R$/US$)",
    "debt_gdp": "BCB SGS 13762 - Divida bruta do governo geral (% PIB)",
    "unemployment": "BCB SGS 24369 - Taxa de desocupacao PNAD Continua (IBGE) (%)",
    "gdp_index": "BCB SGS 22099 - PIB trimestral, indice encadeado (IBGE)",
    "primary_deficit_12m": "BCB SGS 5793 - NFSP primario setor publico consolidado, 12 meses (% PIB, positivo = deficit)",
}


def fetch(code: int, attempts: int = 4) -> list[dict]:
    url = f"https://api.bcb.gov.br/dados/serie/bcdata.sgs.{code}/dados?formato=json&dataInicial={START}&dataFinal={END}"
    for attempt in range(attempts):
        try:
            with urllib.request.urlopen(url, timeout=60) as resp:
                return json.load(resp)
        except Exception:
            if attempt == attempts - 1:
                raise
            time.sleep(2 * (attempt + 1))
    return []


def download() -> None:
    RAW.mkdir(parents=True, exist_ok=True)
    for name, code in SERIES.items():
        (RAW / f"{name}.json").write_text(json.dumps(fetch(code)))


def quarter_of(date: str) -> str:
    day, month, year = date.split("/")
    return f"{year}Q{(int(month) - 1) // 3 + 1}"


def last_by_quarter(name: str) -> dict[str, float]:
    out: dict[str, float] = {}
    for row in json.loads((RAW / f"{name}.json").read_text()):
        out[quarter_of(row["data"])] = float(row["valor"])
    return out


def build() -> dict:
    series = {name: last_by_quarter(name) for name in SERIES}
    shocks = json.loads((DATA / "shocks_2018_2026.json").read_text())["quarters"]
    gdp = series["gdp_index"]
    quarters = []
    for q, shock in shocks.items():
        year, n = int(q[:4]), q[-1]
        prev_year = f"{year - 1}Q{n}"
        if q not in gdp or prev_year not in gdp:
            continue
        quarters.append({
            "q": q,
            "selic": series["selic"][q],
            "brl_usd": series["brl_usd"][q],
            # The engine books primary balance as -0.4 - spending, so this reproduces the observed 12-month result.
            "spending": round(series["primary_deficit_12m"][q] - 0.4, 3),
            **shock,
            "target": {
                "gdp_growth": round((gdp[q] / gdp[prev_year] - 1) * 100, 2),
                "inflation": series["ipca_12m"][q],
                "unemployment": series["unemployment"][q],
                "debt_gdp": series["debt_gdp"][q],
            },
        })
    start_q = "2017Q4"
    start = json.loads((DATA / "shocks_2018_2026.json").read_text())["start_other"]
    return {
        "_note": "Generated by sim/history.py from Banco Central SGS series (raw copies in data/bcb/). Shock intensities come from data/shocks_2018_2026.json.",
        "sources": SOURCES,
        "start": {
            "gdp_growth": round((gdp[start_q] / gdp["2016Q4"] - 1) * 100, 2) if "2016Q4" in gdp else 1.3,
            "inflation": series["ipca_12m"][start_q],
            "selic": series["selic"][start_q],
            "unemployment": series["unemployment"][start_q],
            "debt_gdp": series["debt_gdp"][start_q],
            "primary_balance": -series["primary_deficit_12m"][start_q],
            "brl_usd": series["brl_usd"][start_q],
            **start,
        },
        "quarters": quarters,
    }


def latest() -> dict:
    """Most recent official values, used as the simulation's starting point."""
    out = {}
    for name in ("selic", "ipca_12m", "brl_usd", "debt_gdp", "unemployment", "primary_deficit_12m"):
        rows = json.loads((RAW / f"{name}.json").read_text())
        out[name] = {"date": rows[-1]["data"], "value": float(rows[-1]["valor"])}
    gdp = last_by_quarter("gdp_index")
    q = max(gdp)
    out["gdp_yoy"] = {"quarter": q, "value": round((gdp[q] / gdp[f"{int(q[:4]) - 1}Q{q[-1]}"] - 1) * 100, 2)}
    return out


if __name__ == "__main__":
    import sys

    if "--offline" not in sys.argv:
        download()
    history = build()
    (DATA / "history_2018_2026.json").write_text(json.dumps(history, indent=1))
    print(f"{len(history['quarters'])} quarters: {history['quarters'][0]['q']} .. {history['quarters'][-1]['q']}")
    print(json.dumps(latest(), indent=1))
